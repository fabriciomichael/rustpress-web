//! # RustPress
//!
//! RustPress is a minimalist asynchronous HTTP framework for Rust,
//! built on Hyper and Tokio. The API organizes an application around routes,
//! middleware, requests, responses, templates, and error handling.
//!
//! ## Example
//!
//! ```no_run
//! use rustpress_web::{App, Request, Response};
//!
//! #[tokio::main]
//! async fn main() -> Result<(), Box<dyn std::error::Error + Send + Sync>> {
//!     let mut app = App::new();
//!     app.get("/", |_request: Request, response: Response| {
//!         Ok(response.html("<h1>RustPress está a funcionar</h1>"))
//!     })?;
//!     app.listen("127.0.0.1:3000").await?;
//!     Ok(())
//! }
//! ```
//!
//! ## Default Cargo.toml configuration
//!
//! ```toml
//! [package]
//! name = "project_name"
//! version = "0.1.0"
//! edition = "2024"
//!
//! [dependencies]
//! rustpress-web = "0.2.0"
//! tokio = { version = "1", features = ["full"] }
//! ```
//!
//! ## Public API
//!
//! - [`App`]: application configuration and server startup.
//! - [`RouteGroup`]: route grouping with prefixes and dedicated middleware.
//! - [`Request`] and [`RequestContext`]: request metadata and information.
//! - [`Response`]: HTTP response construction.
//! - [`HandlerError`]: errors returned by handlers.
//! - [`MiddlewareResult`]: advanced middleware chain control.
//! - [`Logger`] and [`Level`]: event logging.
//! - [`TemplateContext`] and [`TemplateError`]: template engine types.
//! - [`security::Password`]: password hash generation and verification.
//! - [`security::PasswordConfig`]: Argon2id parameter configuration.
//! - [`security::PasswordError`]: security module errors.
//! - [`upload::UploadConfig`]: upload limits and storage configuration.
//! - [`upload::UploadError`]: upload processing errors.
//! - [`upload::UploadedFile`]: representation of a received file.
//!
//! The API includes HTTP body reading, URL-encoded form parsing
//! and `multipart/form-data` parsing, cookie and session management,
//! route groups, password security tools, and file uploads.
//!
//! ## File Uploads
//!
//! `multipart/form-data` processing is available through the
//! [`App::use_uploads`] method. The feature must be explicitly enabled
//! and allows configuring limits for total size, individual file size,
//! file count, and field count.
//!
//! Received files are stored using names generated by the framework.
//! Original filenames are provided only as metadata.
//!
//! See [`upload::UploadConfig`] and [`upload::UploadedFile`] for
//! the available configuration options and provided data.
//!
//! Access to received files is provided through
//! [`Request::file`] and [`Request::files`].
//!
//! ## Security
//!
//! The [`security`] module provides password hashing and verification
//! using Argon2id.
//!
//! The [`upload`] module applies size and quantity limits to reduce
//! the risk of excessive resource consumption during upload processing.

